// ============================================================
//  NIVELES
//  Mini-lenguaje de mapas:
//   {c12} = 12 veces el carácter c   ·   {c*} = rellena la fila con c
//   "8*|fila" = repite la fila 8 veces · filas cortas se completan con aire
//  Leyenda:
//   # piedra   I hielo   = tabla (se cruza desde abajo; arde si estás caliente)
//   ^ v [ ] púas (] clavada en muro izquierdo, [ en muro derecho)   ~ lava   C piedra que se desmorona   Q muro agrietado (impulso)
//   H muro falso   D reja  K llave   L palanca  Z/Y compuertas (palanca)
//   R/B bloques que cambian al saltar   ( ) cintas   T chorro de fuego   < > cañón
//   w corriente de aire   1-4 portales   M/N plataforma móvil  | tope
//   S resorte  o orbe  i vela  g bloque fantasma  V respiradero (calor)  f ventisca (frío)
//   x escarcha (se derrite con calor)  _ hielo fino (se rompe con calor)
//   e caminante  b murciélago  y gárgola  j saltarín
//   P inicio  E farol  * chispa dorada  F brasero  c brasa  n pergamino  d corazón de impulso
//   a alas  h escudo  t reloj  + hongo  X jefe
// ============================================================
function _exRow(src,W){
  let out='',fillAt=-1,fillC='';
  for(let i=0;i<src.length;i++){
    if(src[i]==='{'){const j=src.indexOf('}',i),c=src[i+1],n=src.slice(i+2,j);
      if(n==='*'){fillAt=out.length;fillC=c;}else out+=c.repeat(+n);i=j;}
    else out+=src[i];
  }
  if(fillAt>=0)out=out.slice(0,fillAt)+fillC.repeat(Math.max(0,W-out.length))+out.slice(fillAt);
  if(out==='.')out='';
  if(out.length>W)throw new Error('fila demasiado larga ('+out.length+'>'+W+'): '+src);
  return out.padEnd(W,'.');
}
function CH(W,txt){
  const rows=[];
  for(const line of txt.split('\n')){const l=line.trim();if(!l)continue;
    const m=l.match(/^(\d+)\*\|(.*)$/);
    if(m){for(let k=0;k<+m[1];k++)rows.push(_exRow(m[2],W));}else rows.push(_exRow(l,W));}
  return rows;
}
function LV(def,H,...chunks){
  chunks.forEach((c,i)=>{if(c.length!==H)throw new Error(`${def.id}: el tramo ${i+1} tiene ${c.length} filas (esperaba ${H})`);});
  def.map=Array.from({length:H},(_,y)=>chunks.map(c=>c[y]).join(''));
  LEVELS.push(def);
}
